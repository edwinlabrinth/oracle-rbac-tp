-- P_BQ_AGENT : guichetiers (E4 : 1 session, IDLE 10 min, 3 échecs, verrouillage 30 min,
-- vie 60 jours, non réutilisable avant un an, fonction de verification)
PROMPT === Creation du profil P_BQ_AGENT ===
CREATE PROFILE p_bq_agent LIMIT
  SESSIONS_PER_USER 1
  IDLE_TIME 10
  FAILED_LOGIN_ATTEMPTS 3
  PASSWORD_LOCK_TIME 30/1440
  PASSWORD_LIFE_TIME 60
  PASSWORD_GRACE_TIME 7
  PASSWORD_REUSE_TIME 365
  PASSWORD_REUSE_MAX 5
  PASSWORD_VERIFY_FUNCTION ORA12C_VERIFY_FUNCTION;

-- P_BQ_CONSEIL : meme profil que l'agent mais 2 sessions (conseiller)
PROMPT === Creation du profil P_BQ_CONSEIL (2 sessions pour le conseiller) ===
CREATE PROFILE p_bq_conseil LIMIT
  SESSIONS_PER_USER 2
  IDLE_TIME 10
  FAILED_LOGIN_ATTEMPTS 3
  PASSWORD_LOCK_TIME 30/1440
  PASSWORD_LIFE_TIME 60
  PASSWORD_GRACE_TIME 7
  PASSWORD_REUSE_TIME 365
  PASSWORD_REUSE_MAX 5
  PASSWORD_VERIFY_FUNCTION ORA12C_VERIFY_FUNCTION;

-- P_BQ_SENSIBLE : directeur et auditeur, meme regles E4 + E5 (fonction forte)
PROMPT === Creation du profil P_BQ_SENSIBLE (fonction de verification forte) ===
CREATE PROFILE p_bq_sensible LIMIT
  SESSIONS_PER_USER 1
  IDLE_TIME 10
  FAILED_LOGIN_ATTEMPTS 3
  PASSWORD_LOCK_TIME 30/1440
  PASSWORD_LIFE_TIME 60
  PASSWORD_GRACE_TIME 7
  PASSWORD_REUSE_TIME 365
  PASSWORD_REUSE_MAX 5
  PASSWORD_VERIFY_FUNCTION ORA12C_STRONG_VERIFY_FUNCTION;

-- P_BQ_SERVICE : batch, pas d'expiration, durci autrement
PROMPT === Creation du profil P_BQ_SERVICE (batch) ===
CREATE PROFILE p_bq_service LIMIT
  SESSIONS_PER_USER DEFAULT
  IDLE_TIME DEFAULT
  FAILED_LOGIN_ATTEMPTS 5
  PASSWORD_LOCK_TIME 15/1440
  PASSWORD_LIFE_TIME UNLIMITED
  PASSWORD_GRACE_TIME DEFAULT
  PASSWORD_REUSE_TIME 365
  PASSWORD_REUSE_MAX 5
  PASSWORD_VERIFY_FUNCTION ORA12C_STRONG_VERIFY_FUNCTION;

COLUMN profile FORMAT A16
COLUMN resource_name FORMAT A30
COLUMN limit FORMAT A14
PROMPT === Resume des profils Banque ===
SELECT profile, resource_name, limit
  FROM dba_profiles
 WHERE profile IN ('P_BQ_AGENT','P_BQ_CONSEIL','P_BQ_SENSIBLE','P_BQ_SERVICE')
 ORDER BY profile, resource_name;
EXIT
